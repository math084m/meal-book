const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, da };

function detectLanguage(): Language {
  const stored = localStorage.getItem(storageKey);
  if (stored === 'en' || stored === 'da') {
    return stored;
  }
  return navigator.language?.toLowerCase().startsWith('da') ? 'da' : 'en';
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<Language>(detectLanguage());

  constructor() {
    document.documentElement.lang = this.lang();
  }

  setLanguage(language: Language): void {
    localStorage.setItem(storageKey, language);
    document.documentElement.lang = language;
    this.lang.set(language);
  }

  // Reads the language signal, so templates calling this re-render on language change.
  t(key: TranslationKey, params: Record<string, string | number> = {}): string {
    return dictionaries[this.lang()][key].replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match
    );
  }

  languageName(code: string): string {
    return languages.find(item => item.code === code)?.label ?? code;
  }
}
