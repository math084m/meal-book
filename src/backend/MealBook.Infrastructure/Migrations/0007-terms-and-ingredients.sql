CREATE TABLE "RecipeTerms" (
    "RecipeId" uuid NOT NULL,
    "Kind" character varying(40) NOT NULL,
    "Slug" character varying(80) NOT NULL,
    CONSTRAINT "PK_RecipeTerms" PRIMARY KEY ("RecipeId", "Kind", "Slug"),
    CONSTRAINT "FK_RecipeTerms_Recipes_RecipeId"
        FOREIGN KEY ("RecipeId") REFERENCES "Recipes" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_RecipeTerms_Terms"
        FOREIGN KEY ("Kind", "Slug") REFERENCES "Terms" ("Kind", "Slug") ON DELETE RESTRICT
);

CREATE INDEX "IX_RecipeTerms_Kind_Slug" ON "RecipeTerms" ("Kind", "Slug");

-- Best-effort carry-over of the old free-text values onto the premade terms.
INSERT INTO "RecipeTerms" ("RecipeId", "Kind", "Slug")
SELECT DISTINCT r."Id", t."Kind", t."Slug"
FROM "Recipes" r
JOIN "Terms" t
    ON (t."Kind" = 'mealType' AND lower(trim(r."MealType")) IN (lower(t."NameEn"), lower(t."NameDa"), t."Slug"))
    OR (t."Kind" = 'course' AND lower(trim(r."Course")) IN (lower(t."NameEn"), lower(t."NameDa"), t."Slug"))
    OR (t."Kind" = 'cookingMethod' AND lower(trim(r."CookingMethod")) IN (lower(t."NameEn"), lower(t."NameDa"), t."Slug"))
    OR (t."Kind" = 'cuisine' AND lower(trim(r."Cuisine")) IN (lower(t."NameEn"), lower(t."NameDa"), t."Slug"));

INSERT INTO "RecipeTerms" ("RecipeId", "Kind", "Slug")
SELECT DISTINCT g."RecipeId", t."Kind", t."Slug"
FROM "RecipeTagEntity" g
JOIN "Terms" t
    ON t."Kind" = 'tag' AND lower(trim(g."Name")) IN (lower(t."NameEn"), lower(t."NameDa"), t."Slug")
ON CONFLICT DO NOTHING;

