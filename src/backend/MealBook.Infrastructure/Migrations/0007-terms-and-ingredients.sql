-- Existing free-text ingredients that are not in the premade list become catalog entries.
INSERT INTO "Ingredients" ("Id", "NameEn", "NameDa")
SELECT gen_random_uuid(), n, n
FROM (
    SELECT DISTINCT ON (lower(trim(ri."Name"))) trim(ri."Name") AS n
    FROM "RecipeIngredientEntity" ri
    WHERE NOT EXISTS (
        SELECT 1 FROM "Ingredients" i
        WHERE lower(i."NameEn") = lower(trim(ri."Name")) OR lower(i."NameDa") = lower(trim(ri."Name")))
) missing;

ALTER TABLE "RecipeIngredientEntity" ADD COLUMN "IngredientId" uuid NULL;

UPDATE "RecipeIngredientEntity" ri
SET "IngredientId" = (
    SELECT i."Id"
    FROM "Ingredients" i
    WHERE lower(i."NameEn") = lower(trim(ri."Name")) OR lower(i."NameDa") = lower(trim(ri."Name"))
    ORDER BY (lower(i."NameEn") = lower(trim(ri."Name"))) DESC, i."NameEn"
    LIMIT 1);

ALTER TABLE "RecipeIngredientEntity"
